/* =====================================================================
   BANCO DE DADOS I — Base para exercícios de JOIN
   Plataforma de cursos online (fictícia) — matrículas de 2024 e 2025
   ---------------------------------------------------------------------
   Abra no Query Tool de qualquer database (sugestão: cursos) e
   aperte F5. O script apaga as tabelas, se existirem, e recria tudo.
   Os dados são sempre os mesmos para toda a turma.

   TABELAS E LIGAÇÕES

     instrutores (id_instrutor)
          |
          | cursos.id_instrutor  (pode ser vazio: curso sem instrutor definido)
          |
     cursos (id_curso)                     alunos (id_aluno)
          |                                     |
          | matriculas.id_curso                 | matriculas.id_aluno
          +------------- matriculas ------------+
                         (id_matricula)
                              |
                              | avaliacoes.id_matricula
                              |
                         avaliacoes (id_avaliacao)

     * Uma matrícula = um aluno em um curso.
     * Uma avaliação = a nota (1 a 5) dada por um aluno ao concluir
       uma matrícula. Nem toda matrícula concluída foi avaliada.
   ===================================================================== */

DROP TABLE IF EXISTS avaliacoes;
DROP TABLE IF EXISTS matriculas;
DROP TABLE IF EXISTS alunos;
DROP TABLE IF EXISTS cursos;
DROP TABLE IF EXISTS instrutores;

CREATE TABLE instrutores (
    id_instrutor      INTEGER      NOT NULL,
    nome              VARCHAR(80)  NOT NULL,
    especialidade     VARCHAR(30)  NOT NULL,
    data_contratacao  DATE         NOT NULL,
    CONSTRAINT pk_instrutores PRIMARY KEY (id_instrutor)
);

CREATE TABLE cursos (
    id_curso       INTEGER       NOT NULL,
    titulo         VARCHAR(80)   NOT NULL,
    categoria      VARCHAR(30)   NOT NULL,
    carga_horaria  SMALLINT      NOT NULL,
    preco          NUMERIC(8,2)  NOT NULL,
    id_instrutor   INTEGER,
    CONSTRAINT pk_cursos PRIMARY KEY (id_curso),
    CONSTRAINT uq_cursos_titulo UNIQUE (titulo),
    CONSTRAINT fk_cursos_instrutores
        FOREIGN KEY (id_instrutor) REFERENCES instrutores (id_instrutor)
);

CREATE TABLE alunos (
    id_aluno       INTEGER       NOT NULL,
    nome           VARCHAR(80)   NOT NULL,
    email          VARCHAR(120)  NOT NULL,
    cidade         VARCHAR(40)   NOT NULL,
    uf             CHAR(2)       NOT NULL,
    data_cadastro  DATE          NOT NULL,
    CONSTRAINT pk_alunos PRIMARY KEY (id_aluno),
    CONSTRAINT uq_alunos_email UNIQUE (email)
);

CREATE TABLE matriculas (
    id_matricula    INTEGER       NOT NULL,
    id_aluno        INTEGER       NOT NULL,
    id_curso        INTEGER       NOT NULL,
    data_matricula  DATE          NOT NULL,
    valor_pago      NUMERIC(8,2)  NOT NULL,
    status          VARCHAR(15)   NOT NULL,
    CONSTRAINT pk_matriculas PRIMARY KEY (id_matricula),
    CONSTRAINT uq_matriculas_aluno_curso UNIQUE (id_aluno, id_curso),
    CONSTRAINT fk_matriculas_alunos
        FOREIGN KEY (id_aluno) REFERENCES alunos (id_aluno),
    CONSTRAINT fk_matriculas_cursos
        FOREIGN KEY (id_curso) REFERENCES cursos (id_curso),
    CONSTRAINT ck_matriculas_status
        CHECK (status IN ('Concluída', 'Em andamento', 'Cancelada'))
);

CREATE TABLE avaliacoes (
    id_avaliacao    INTEGER   NOT NULL,
    id_matricula    INTEGER   NOT NULL,
    nota            SMALLINT  NOT NULL,
    data_avaliacao  DATE      NOT NULL,
    CONSTRAINT pk_avaliacoes PRIMARY KEY (id_avaliacao),
    CONSTRAINT uq_avaliacoes_matricula UNIQUE (id_matricula),
    CONSTRAINT fk_avaliacoes_matriculas
        FOREIGN KEY (id_matricula) REFERENCES matriculas (id_matricula),
    CONSTRAINT ck_avaliacoes_nota CHECK (nota BETWEEN 1 AND 5)
);

